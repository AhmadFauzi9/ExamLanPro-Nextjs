CREATE TABLE IF NOT EXISTS users (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, username VARCHAR(80) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL, name VARCHAR(120) NOT NULL, role ENUM('ADMIN','TEACHER') NOT NULL DEFAULT 'TEACHER',
  must_change_password BOOLEAN NOT NULL DEFAULT TRUE, last_login_at DATETIME NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS students (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, nis VARCHAR(40) NOT NULL UNIQUE, name VARCHAR(150) NOT NULL,
  class_name VARCHAR(80) NOT NULL, section_name VARCHAR(80) NULL, homeroom_teacher VARCHAR(150) NULL,
  photo_url VARCHAR(500) NULL, password_hash VARCHAR(255) NULL, active BOOLEAN NOT NULL DEFAULT TRUE,
  deleted_at DATETIME NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_student_class(class_name, section_name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS quizzes (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, title VARCHAR(200) NOT NULL, subject VARCHAR(120) NOT NULL,
  class_name VARCHAR(80) NOT NULL, description TEXT NULL, duration_minutes INT UNSIGNED NOT NULL DEFAULT 60,
  max_questions INT UNSIGNED NULL DEFAULT 0,
  start_at DATETIME NULL DEFAULT NULL, end_at DATETIME NULL DEFAULT NULL, exam_token CHAR(6) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
  token_enabled BOOLEAN NOT NULL DEFAULT TRUE, randomize_questions BOOLEAN NOT NULL DEFAULT TRUE,
  randomize_options BOOLEAN NOT NULL DEFAULT TRUE, status ENUM('DRAFT','PUBLISHED','ARCHIVED') NOT NULL DEFAULT 'DRAFT',
  review_enabled BOOLEAN NOT NULL DEFAULT FALSE, kkm DECIMAL(5,2) NOT NULL DEFAULT 75, created_by BIGINT UNSIGNED NOT NULL,
  deleted_at DATETIME NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_quiz_user FOREIGN KEY(created_by) REFERENCES users(id), CHECK(start_at IS NULL OR end_at IS NULL OR end_at > start_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS questions (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, quiz_id BIGINT UNSIGNED NOT NULL, position INT UNSIGNED NOT NULL,
  type ENUM('mc','complex','cause_effect','case_analysis','matching','essay','scaled') NOT NULL,
  content TEXT NOT NULL, passage TEXT NULL, image_url VARCHAR(500) NULL, options JSON NULL, answer_key JSON NULL,
  explanation TEXT NULL, points DECIMAL(8,2) NOT NULL DEFAULT 1, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_question_position(quiz_id, position), CONSTRAINT fk_question_quiz FOREIGN KEY(quiz_id) REFERENCES quizzes(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS attempts (
  id CHAR(36) PRIMARY KEY, quiz_id BIGINT UNSIGNED NOT NULL, student_id BIGINT UNSIGNED NOT NULL,
  resume_token_hash CHAR(64) NOT NULL, status ENUM('IN_PROGRESS','SUBMITTED','FORCED','EXPIRED') NOT NULL DEFAULT 'IN_PROGRESS',
  question_order JSON NOT NULL, option_orders JSON NULL, started_at DATETIME NOT NULL, expires_at DATETIME NOT NULL,
  submitted_at DATETIME NULL, last_seen_at DATETIME NULL, extra_minutes INT NOT NULL DEFAULT 0,
  score DECIMAL(7,2) NULL, correct_count INT NULL, wrong_count INT NULL, manual_review_required BOOLEAN NOT NULL DEFAULT FALSE,
  ip_address VARCHAR(64) NULL, user_agent VARCHAR(500) NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_quiz_student_attempt(quiz_id, student_id, status), INDEX idx_attempt_monitor(status, last_seen_at),
  CONSTRAINT fk_attempt_quiz FOREIGN KEY(quiz_id) REFERENCES quizzes(id), CONSTRAINT fk_attempt_student FOREIGN KEY(student_id) REFERENCES students(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS attempt_answers (
  attempt_id CHAR(36) NOT NULL, question_id BIGINT UNSIGNED NOT NULL, answer JSON NULL, is_correct BOOLEAN NULL,
  awarded_points DECIMAL(8,2) NULL, saved_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY(attempt_id, question_id), CONSTRAINT fk_answer_attempt FOREIGN KEY(attempt_id) REFERENCES attempts(id) ON DELETE CASCADE,
  CONSTRAINT fk_answer_question FOREIGN KEY(question_id) REFERENCES questions(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS violations (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, attempt_id CHAR(36) NOT NULL, type VARCHAR(80) NOT NULL,
  detail VARCHAR(500) NULL, occurred_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_violation_attempt FOREIGN KEY(attempt_id) REFERENCES attempts(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS extension_requests (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, attempt_id CHAR(36) NOT NULL,
  status ENUM('PENDING','APPROVED','REJECTED') NOT NULL DEFAULT 'PENDING', requested_minutes INT UNSIGNED NOT NULL DEFAULT 15,
  approved_minutes INT UNSIGNED NULL, reason VARCHAR(500) NULL, decided_by BIGINT UNSIGNED NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, decided_at DATETIME NULL,
  CONSTRAINT fk_ext_attempt FOREIGN KEY(attempt_id) REFERENCES attempts(id) ON DELETE CASCADE,
  CONSTRAINT fk_ext_user FOREIGN KEY(decided_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS audit_logs (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, actor VARCHAR(120) NOT NULL, action VARCHAR(120) NOT NULL,
  entity VARCHAR(80) NULL, entity_id VARCHAR(80) NULL, detail JSON NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_audit_created(created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS app_settings (
  setting_key VARCHAR(120) PRIMARY KEY, setting_value JSON NOT NULL, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

